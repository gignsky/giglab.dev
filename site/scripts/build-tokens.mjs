// Generates src/styles/tokens.css from docs/design/tokens.json, so the two
// never drift apart. Re-run via `npm run tokens` (also wired into dev/build).
// Never hand-edit tokens.css -- edit tokens.json and regenerate.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const tokensPath = path.resolve(here, '../../docs/design/tokens.json');
const outPath = path.resolve(here, '../src/styles/tokens.css');

const tokens = JSON.parse(readFileSync(tokensPath, 'utf8'));

const colorLines = (theme) =>
  tokens.color.tokens.map((t) => `  --${t.name}: ${t.value[theme]};`).join('\n');

const spacingLines = tokens.spacing.tokens.map((t) => `  --${t.name}: ${t.value};`).join('\n');
const radiusLines = tokens.radius.tokens.map((t) => `  --${t.name}: ${t.value};`).join('\n');

const fontLines = Object.entries(tokens.type.families)
  .map(([name, value]) => `  --font-${name}: ${value};`)
  .join('\n');

const css = `/* Generated by site/scripts/build-tokens.mjs from docs/design/tokens.json.
 * Do not hand-edit -- edit tokens.json and run \`npm run tokens\`. */

:root {
${colorLines('dark')}
${spacingLines}
${radiusLines}
${fontLines}
}

/* Respect the system theme when no explicit choice has been made. A manual
 * toggle is out of scope for the landing page (docs/design/landing-annunciator.md). */
@media (prefers-color-scheme: light) {
  :root:not([data-theme='dark']) {
${colorLines('light')}
  }
}

/* Explicit override, forward-compatible with a future theme toggle. */
:root[data-theme='light'] {
${colorLines('light')}
}

:root[data-theme='dark'] {
${colorLines('dark')}
}
`;

writeFileSync(outPath, css);
console.log(`wrote ${path.relative(process.cwd(), outPath)}`);
